CREATE TABLE IF NOT EXISTS products (
    id INTEGER PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    category VARCHAR(40) NOT NULL,
    price DECIMAL(12,2) NOT NULL CHECK (price >= 0),
    stock INTEGER NOT NULL CHECK (stock >= 0)
);
CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS shop_orders (
    id VARCHAR(36) PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    placed_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    subtotal DECIMAL(14,2) NOT NULL CHECK (subtotal >= 0),
    discount DECIMAL(14,2) NOT NULL CHECK (discount >= 0 AND discount <= subtotal),
    total DECIMAL(14,2) NOT NULL CHECK (total = subtotal - discount)
);
CREATE TABLE IF NOT EXISTS order_items (
    order_id VARCHAR(36) NOT NULL REFERENCES shop_orders(id),
    product_id INTEGER NOT NULL REFERENCES products(id),
    product_name VARCHAR(100) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price DECIMAL(12,2) NOT NULL CHECK (unit_price >= 0),
    PRIMARY KEY (order_id, product_id)
);

